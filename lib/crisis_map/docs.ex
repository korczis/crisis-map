defmodule CrisisMap.Docs do
  @moduledoc """
  Documentation, inferred.

  Every reference document in `docs/` and every page of the published site is
  rendered from the capability registry and the catalog. Nothing here is
  hand-written prose about what an operation does — that prose lives on the
  declaration, which is also what generates the route, the OpenAPI operation
  and the MCP tool, so the documentation cannot describe a system that is not
  the one running.

  `mix crisis_map.docs` writes the files, `mix crisis_map.docs --check` fails
  when what is committed differs from what the registry would produce now.
  That check runs in CI, which is what keeps them in sync.
  """

  alias CrisisMap.Capabilities
  alias CrisisMap.Capability
  alias CrisisMap.Catalog

  @generated_notice "<!-- Generated by `mix crisis_map.docs` from CrisisMap.Capabilities. Do not edit by hand. -->"

  @doc "Every generated file, as a map of repository path to content."
  @spec files() :: %{String.t() => String.t()}
  def files do
    %{
      "docs/CAPABILITIES.md" => capabilities_markdown(),
      "docs/CATALOG.md" => catalog_markdown()
    }
  end

  @doc "The capability reference."
  @spec capabilities_markdown() :: String.t()
  def capabilities_markdown do
    capabilities = Capabilities.all()

    """
    #{@generated_notice}

    # Capabilities

    #{length(capabilities)} operations, each declared once in
    `lib/crisis_map/capabilities.ex` and projected onto every surface: the
    command line, the JSON API, the OpenAPI document, the MCP tool list and the
    cockpit.

    | Capability | HTTP | Summary |
    |---|---|---|
    #{Enum.map_join(capabilities, "\n", &index_row/1)}

    #{Enum.map_join(capabilities, "\n", &capability_section/1)}
    """
  end

  defp index_row(capability) do
    "| `#{capability.name}` | `#{Capability.http(capability)}` | #{capability.summary} |"
  end

  defp capability_section(%Capability{} = capability) do
    """
    ## `#{capability.name}`

    #{String.trim(capability.description)}

    | | |
    |---|---|
    | HTTP | `#{Capability.http(capability)}` |
    | CLI | `#{Capability.cli(capability)}` |
    | MCP tool | `#{Capability.tool_name(capability)}` |
    | Tags | #{Enum.map_join(capability.tags, ", ", &"`#{&1}`")} |
    | Mutating | #{if capability.mutating, do: "yes", else: "no"} |

    **Returns.** #{capability.returns}

    #{params_section(capability)}
    #{examples_section(capability)}
    """
  end

  defp params_section(%Capability{params: []}), do: "This capability takes no parameters.\n"

  defp params_section(%Capability{params: params}) do
    """
    ### Parameters

    | Name | Type | Required | Description |
    |---|---|---|---|
    #{Enum.map_join(params, "\n", &param_row/1)}
    """
  end

  defp param_row(param) do
    required = if Map.get(param, :required, false), do: "yes", else: "no"
    "| `#{param.name}` | `#{param.type}` | #{required} | #{param.description} |"
  end

  defp examples_section(%Capability{examples: []}), do: ""

  defp examples_section(%Capability{} = capability) do
    """
    ### Examples

    #{Enum.map_join(capability.examples, "\n", &example_line(capability, &1))}
    """
  end

  defp example_line(capability, example) do
    args =
      Enum.map_join(example.params, " ", fn {key, value} ->
        "--#{Capability.dashed(key)} #{inspect(value)}"
      end)

    "* #{example.description}:\n  ```\n  mix crisis_map.run #{capability.name} #{args}\n  ```"
  end

  @doc "The catalog reference: the vocabulary every surface shares."
  @spec catalog_markdown() :: String.t()
  def catalog_markdown do
    """
    #{@generated_notice}

    # Catalog

    The vocabulary of the domain, declared in `lib/crisis_map/catalog.ex`. The
    Ecto changeset, the LiveView filter, the map colours, the API and this page
    all read it from there; none of them keeps a copy.

    ## Event types

    | Id | Label | Colour | Meaning |
    |---|---|---|---|
    #{Enum.map_join(Catalog.event_types(), "\n", fn type -> "| `#{type.id}` | #{type.label} | `#{type.color}` | #{type.description} |" end)}

    A source type that is not in this list is filed under
    `#{Catalog.fallback_event_type()}` rather than rejected: losing an event
    because a source invented a label would be worse than filing it as other.

    ## Geocoding statuses

    Every state a position can be in. The schema enforces the pairing between a
    status and the presence of coordinates, so "we know where this is" and "we
    have no coordinates" can never both be true of one row.

    | Id | Coordinates known | Meaning |
    |---|---|---|
    #{Enum.map_join(Catalog.geocoding_statuses(), "\n", fn status -> "| `#{status.id}` | #{if status.coordinates_known, do: "yes", else: "no"} | #{status.description} |" end)}

    ## Reference points

    Fixed centres offered by the radius search.

    | Id | Label | Latitude | Longitude |
    |---|---|---|---|
    #{Enum.map_join(Catalog.reference_points(), "\n", fn point -> "| `#{point.id}` | #{point.label} | #{point.lat} | #{point.lon} |" end)}
    """
  end
end
